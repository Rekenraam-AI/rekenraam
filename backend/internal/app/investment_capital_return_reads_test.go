func TestCapitalReturnReadUsesLatestWholeSetAndRetainsRetiredHistory(t *testing.T) {
	t.Parallel()
	f := newInvestmentsTestFixture(t)
	ctx := context.Background()
	buy := buyOn(t, f, "2026-05-01", 1, 700)
	input := capitalReturnInput(f, "2026-06-01", 1000)
	input.PaymentOn = "2026-06-10"
	receipt, err := f.investmentService.CapitalReturn(ctx, input)
	require.NoError(t, err)
	before := f.transactionCount(t)
	reads, err := f.investmentService.ListCapitalReturns(ctx, GainsReportParams{})
	require.NoError(t, err)
	require.Len(t, reads, 1)
	original := reads[0]
	require.Equal(t, input.SourceEvidenceJSON, original.SourceEvidenceJSON)
	require.Equal(t, input.EffectiveOn, original.EffectiveOn)
	require.Equal(t, input.PaymentOn, original.PaymentOn)
	require.True(t, original.Effective)
	require.True(t, original.HasExcess)
	requireScaled(t, 700, 2, coefScaled(original.ReductionValue, original.ReductionScale), "recorded reduction")
	requireScaled(t, 300, 2, coefScaled(original.ExcessValue, original.ExcessScale), "recorded excess")
	require.Equal(t, before, f.transactionCount(t), "reading never posts")
	for _, period := range []GainsReportParams{{To: "2026-06-09"}, {From: "2026-06-11"}} {
		reads, err = f.investmentService.ListCapitalReturns(ctx, period)
		require.NoError(t, err)
		require.Empty(t, reads, "filter uses receipt date")
	}
	reads, err = f.investmentService.ListCapitalReturns(ctx, GainsReportParams{From: input.PaymentOn, To: input.PaymentOn})
	require.NoError(t, err)
	require.Len(t, reads, 1)
	replacement, err := acknowledgedReplaceBuy(ctx, f.investmentService, replaceBuyPrice(f, buy, "2026-05-01", 1, 500))
	require.NoError(t, err)
	reads, err = f.investmentService.ListCapitalReturns(ctx, GainsReportParams{})
	require.NoError(t, err)
	require.Len(t, reads, 1)
	require.Equal(t, 2, reads[0].RevisionSeq)
	require.Positive(t, reads[0].RevisionID)
	require.NotEqual(t, original.AuditEventID, reads[0].AuditEventID)
	require.Len(t, reads[0].Effects, 1)
	require.Equal(t, *replacement.Replacement.LotID, reads[0].Effects[0].LotID, "no original lot mixed into revised set")
	requireScaled(t, 500, 2, coefScaled(reads[0].ExcessValue, reads[0].ExcessScale), "latest revised excess")
	second, err := acknowledgedReplaceBuy(ctx, f.investmentService, replaceBuyPrice(f, replacement.Replacement, "2026-05-01", 1, 1200))
	require.NoError(t, err)
	reads, err = f.investmentService.ListCapitalReturns(ctx, GainsReportParams{})
	require.NoError(t, err)
	require.Len(t, reads, 1)
	require.Equal(t, 3, reads[0].RevisionSeq)
	require.False(t, reads[0].HasExcess)
	requireScaled(t, 0, 2, coefScaled(reads[0].ExcessValue, reads[0].ExcessScale), "latest no excess")
	requireScaled(t, 200, 2, lotRemainingBasis(t, f, *second.Replacement.LotID), "view leaves basis intact")
	chain, err := f.investmentService.CorrectionChain(ctx, f.ownerUserID, receipt.Transaction.ID)
	require.NoError(t, err)
	require.Len(t, chain.CapitalReturns, 3)
	require.Equal(t, original.Effects, chain.CapitalReturns[0].Effects)
	require.False(t, chain.CapitalReturns[0].Effective)
	require.False(t, chain.CapitalReturns[1].Effective)
	require.True(t, chain.CapitalReturns[2].Effective)
	// Receipt replacement retires all prior sets, while original evidence stays.
	corrected, err := f.investmentService.ReplaceCapitalReturn(ctx, ReplaceInvestmentCapitalReturnInput{
		OwnerUserID: f.ownerUserID, TransactionID: receipt.Transaction.ID, Reason: "corrected receipt", Replacement: capitalReturnInput(f, "2026-06-01", 1500),
	})
	require.NoError(t, err)
	reads, err = f.investmentService.ListCapitalReturns(ctx, GainsReportParams{})
	require.NoError(t, err)
	require.Len(t, reads, 1)
	require.Equal(t, corrected.Replacement.Transaction.ID, reads[0].TransactionID)
	requireScaled(t, 300, 2, coefScaled(reads[0].ExcessValue, reads[0].ExcessScale), "replacement excess")
	_, err = f.investmentService.ReverseCapitalReturn(ctx, ReverseInvestmentCapitalReturnInput{OwnerUserID: f.ownerUserID, TransactionID: corrected.Replacement.Transaction.ID, Reason: "withdrawn notice"})
	require.NoError(t, err)
	reads, err = f.investmentService.ListCapitalReturns(ctx, GainsReportParams{})
	require.NoError(t, err)
	require.Empty(t, reads, "reversed actions have no outstanding excess")
	chain, err = f.investmentService.CorrectionChain(ctx, f.ownerUserID, receipt.Transaction.ID)
	require.NoError(t, err)
	require.Len(t, chain.CapitalReturns, 4)
	for _, read := range chain.CapitalReturns {
		require.False(t, read.Effective)
	}
	gains, err := f.investmentService.ListRealizedGains(ctx, GainsReportParams{})
	require.NoError(t, err)
	require.Empty(t, gains, "capital return excess never joins disposal gains")
	requireInvestmentSelfCheckPasses(t, f)
}

func TestCapitalReturnReadKeepsUnknownTotalsAndIndependentKnownEffects(t *testing.T) {
	t.Parallel()
	f := newInvestmentsTestFixture(t)
	ctx := context.Background()
	seedExternalTransferEquity(t, f.database)
	transfer, err := f.investmentService.ExternalTransferIn(ctx, unknownTransferInInput(f, "2026-01-01", ""))
	require.NoError(t, err)
	buyOn(t, f, "2026-02-01", 2, 600)
	receipt, err := f.investmentService.CapitalReturn(ctx, capitalReturnInput(f, "2026-03-01", 2000))
	require.NoError(t, err)
	snapshot := buyReplacementPreviewSnapshot(t, f.database)
	reads, err := f.investmentService.ListCapitalReturns(ctx, GainsReportParams{})
	require.NoError(t, err)
	require.Len(t, reads, 1)
	require.Equal(t, 1, reads[0].UnknownLots)
	require.True(t, reads[0].HasExcess, "independent known excess stays discoverable")
	require.Len(t, reads[0].Effects, 2)
	require.Equal(t, "unknown", reads[0].Effects[0].BasisKnowledge)
	require.Equal(t, "known", reads[0].Effects[1].BasisKnowledge)
	requireScaled(t, 400, 2, coefScaled(reads[0].Effects[1].ExcessValue, reads[0].Effects[1].ExcessScale), "known lot's unresolved excess")
	chain, err := f.investmentService.CorrectionChain(ctx, f.ownerUserID, receipt.Transaction.ID)
	require.NoError(t, err)
	require.Len(t, chain.CapitalReturns, 1)
	require.Equal(t, snapshot, buyReplacementPreviewSnapshot(t, f.database), "composed GET reads never change durable facts or projections")
	resolveAcknowledged(t, f, resolveInput(f, transfer.Transaction.ID, 700))
	reads, err = f.investmentService.ListCapitalReturns(ctx, GainsReportParams{})
	require.NoError(t, err)
	require.Len(t, reads, 1)
	require.Zero(t, reads[0].UnknownLots)
	require.Equal(t, 2, reads[0].RevisionSeq)
	requireScaled(t, 700, 2, coefScaled(reads[0].ExcessValue, reads[0].ExcessScale), "resolved effects total exactly")
	requireInvestmentSelfCheckPasses(t, f)
}
